class EmergencyFacilityStore:
    """Thread-safe in-memory store for emergency facility data."""

    def __init__(self):
        self._lock = threading.Lock()
        self._hospitals = list(GOVERNMENT_HOSPITALS)
        self._fire_stations = list(FIRE_STATIONS)
        self._police_stations = list(POLICE_STATIONS)
        self._traffic_police = list(TRAFFIC_POLICE)
        self._contacts = list(EMERGENCY_CONTACTS)

    def get_all(self, facility_type: Optional[str] = None) -> List[Dict]:
        """Get all facilities, optionally filtered by type."""
        with self._lock:
            if facility_type == "hospital":
                return list(self._hospitals)
            elif facility_type == "fire":
                return list(self._fire_stations)
            elif facility_type == "police":
                return list(self._police_stations)
            elif facility_type == "traffic_police":
                return list(self._traffic_police)
            else:
                return self._hospitals + self._fire_stations + self._police_stations + self._traffic_police

    def get_hospitals(self) -> List[Dict]:
        with self._lock:
            return list(self._hospitals)

    def get_fire_stations(self) -> List[Dict]:
        with self._lock:
            return list(self._fire_stations)

    def get_police_stations(self) -> List[Dict]:
        with self._lock:
            return list(self._police_stations)

    def get_traffic_police(self) -> List[Dict]:
        with self._lock:
            return list(self._traffic_police)

    def get_contacts(self) -> List[Dict]:
        with self._lock:
            return list(self._contacts)

    def search(self, query: str) -> Dict:
        """Search facilities by name, type, address, or jurisdiction."""
        q = query.lower()
        results = {"hospitals": [], "fire_stations": [], "police_stations": [], "traffic_police": []}
        with self._lock:
            for f in self._hospitals:
                if self._matches(f, q):
                    results["hospitals"].append(f)
            for f in self._fire_stations:
                if self._matches(f, q):
                    results["fire_stations"].append(f)
            for f in self._police_stations:
                if self._matches(f, q):
                    results["police_stations"].append(f)
            for f in self._traffic_police:
                if self._matches(f, q):
                    results["traffic_police"].append(f)
        return results

    def _matches(self, facility: Dict, query: str) -> bool:
        searchable = " ".join([
            facility.get("name", ""),
            facility.get("type", ""),
            facility.get("address", ""),
            facility.get("jurisdiction", ""),
            facility.get("category", ""),
        ]).lower()
        return query in searchable

    def summary(self) -> Dict:
        with self._lock:
            return {
                "hospitals": len(self._hospitals),
                "fire_stations": len(self._fire_stations),
                "police_stations": len(self._police_stations),
                "traffic_police": len(self._traffic_police),
                "total_facilities": (
                    len(self._hospitals) + len(self._fire_stations) +
                    len(self._police_stations) + len(self._traffic_police)
                ),
                "emergency_contacts": len(self._contacts),
                "scope": "Chennai Metropolitan Area",
                "classification": "Government / Public facilities only",
                "source": "Tamil Nadu Government, Chennai City Police, Chennai Fire and Rescue Services",
            }


